// Helper to generate songs from a large pool to avoid duplicates
const generateUniqueSongs = (count: number, prefix: string, pool: {title: string, artist: string}[], cover: string) => {
  return Array.from({ length: count }, (_, i) => {
    const item = pool[i % pool.length];
    // If we exceed pool size, append a variation suffix
    const suffix = i >= pool.length ? ` (Mix ${Math.floor(i / pool.length)})` : "";
    return {
      id: `${prefix}_${i + 1}`,
      title: `${item.title}${suffix}`,
      artist: item.artist,
      cover: cover,
      src: "",
      duration: getDuration(i)
    };
  });
};

